const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const TagDraftCore=require('../prototypes/tag-draft-core');
const SearchCore=require('../search-core');
const saved={version:1,edits:{sample:{customTags:['편곡'],removedAutoTags:['원본']}},aliasCache:{'편곡':{aliases:[],source:'unresolved'}}};
const writes=[];
const node={querySelector:()=>({}),append:()=>{}};
const context={TagDraftCore,SearchCore,document:{createElement:()=>node,body:node},localStorage:{getItem:()=>JSON.stringify(saved),setItem:(key,value)=>writes.push({key,value})}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('prototypes/tag-editor.js','utf8'),context);
const editor=context.createTagEditor([{id:'sample',tags:['원본'],aliases:{},title:'fixture'}],()=>{});
assert.equal(writes.length,1);
const restored=JSON.parse(writes[0].value);
assert.deepEqual(restored.edits,saved.edits);
assert.deepEqual(restored.aliasCache['편곡'],{aliases:['arrangement'],source:'local-dictionary'});
assert(SearchCore.matches(editor.videos()[0],'arrangement','tags'));
assert(!editor.videos()[0].tags.includes('원본'));
context.localStorage.getItem=()=>writes[0].value;
context.createTagEditor([],()=>{});
assert.equal(writes.length,1,'unchanged restored cache does not write again');
console.log('Passed real editor startup with mocked DOM/storage: unresolved migration, edit preservation, no repeated writes.');
const elements=new Map();
const makeNode=()=>({children:[],append(child){this.children.push(child);},replaceChildren(){this.children=[];},showModal(){},querySelector(selector){if(!elements.has(selector))elements.set(selector,makeNode());return elements.get(selector);}});
const hiddenStore={version:1,edits:{sample:{customTags:[],removedAutoTags:['사운드디자인']}},aliasCache:{}};
const hiddenContext={TagDraftCore,SearchCore,document:{createElement:makeNode,body:makeNode()},localStorage:{getItem:()=>JSON.stringify(hiddenStore),setItem(){}}};
vm.createContext(hiddenContext);vm.runInContext(fs.readFileSync('prototypes/tag-editor.js','utf8'),hiddenContext);
const source={id:'sample',title:'fixture',tags:['사운드 디자인'],aliases:{}};
const hiddenEditor=hiddenContext.createTagEditor([source],()=>{});
hiddenEditor.open(source);
const restore=elements.get('[data-auto]').children[0];
assert.equal(restore.textContent,'사운드 디자인 복원');
assert.equal(restore.className,'removed');
restore.onclick();
assert.equal(elements.get('[data-auto]').children[0].textContent,'사운드 디자인 ×');
assert.equal(hiddenEditor.videos()[0].tags[0],'사운드 디자인');
console.log('Passed actual editor render and restore click for respelled hidden tags in mocked DOM.');
hiddenContext.localStorage.setItem=()=>{throw Error('fixture quota exceeded');};
elements.get('[data-auto]').children[0].onclick();
assert(elements.get('[data-save]').textContent.includes('저장 실패'));
hiddenEditor.open(source);
assert(elements.get('[data-save]').textContent.includes('저장 실패'),'reopening must retain failed-save warning');
const retryButton=hiddenContext.document.body.children[0].children.find(child=>child.textContent==='다시 저장');
assert.equal(retryButton.hidden,false);
hiddenContext.localStorage.setItem=()=>{};
retryButton.onclick();
assert.equal(retryButton.hidden,true);
assert.equal(elements.get('[data-save]').textContent,'로컬 저장됨');
console.log('Passed failed save warning persistence and explicit retry recovery in mocked storage.');
elements.get('input').value='미제출 입력';
hiddenEditor.open(source);
assert.equal(elements.get('input').value,'','reopening must clear unsubmitted input');
const other={id:'other',title:'second fixture',tags:['다른 원본'],aliases:{}};
const switchingEditor=hiddenContext.createTagEditor([source,other],()=>{});
switchingEditor.open(source);
elements.get('input').value='앞 영상용 미제출 입력';
switchingEditor.open(other);
assert.equal(elements.get('input').value,'','unsubmitted input must not transfer between videos');
assert.equal(elements.get('[data-title]').textContent,'second fixture');
assert.equal(switchingEditor.videos()[1].tags[0],'다른 원본');
console.log('Passed editor reopen and video switch without carrying unsubmitted tag input.');
