const assert=require('node:assert/strict');
const fs=require('node:fs');
const format=require('../prototypes/bookmark-format.cjs');
const id='0gKJ3pgIqI0';
const input=`https://www.youtube.com/watch?v=${id}&t=1m27s`;
assert.equal(format.register(input,{outcome:'failed'}),null);
assert.equal(format.register(input,{outcome:'success',tags:[]}),null);
const registration=format.register(input,{outcome:'success',tags:['베이스','사운드디자인'],aliases:{'베이스':['bass']}});
const initial=format.unpack(registration.url);
assert.equal(initial.kind,'managed');assert.equal(initial.record.positionSeconds,87);assert.equal(initial.record.status,'watching');
const edited={...initial.record,status:'completed',autoTags:['베이스','사운드 디자인'],customTags:['상시 연습','기호 # / & + ? 😀'],removedAutoTags:['사운드 디자인'],aliases:{'베이스':['bass'],'상시 연습':['regular practice']},positionSeconds:347};
const encoded=format.pack(input,edited),restored=format.unpack(encoded);
assert.equal(restored.kind,'managed');assert.deepEqual(restored.record,edited);
assert.equal(format.pack(encoded,restored.record),encoded);
const regenerated=format.register(encoded,{outcome:'success',tags:['새 자동 태그'],aliases:{'새 자동 태그':['new automatic tag'],'상시 연습':['wrong replacement']}});
const refreshed=format.unpack(regenerated.url).record;
assert.deepEqual(refreshed.customTags,edited.customTags);
assert.deepEqual(refreshed.removedAutoTags,edited.removedAutoTags);
assert.deepEqual(refreshed.aliases['상시 연습'],['regular practice']);
assert.deepEqual(refreshed.autoTags,['새 자동 태그']);
assert.equal(refreshed.status,'completed');
assert.equal(refreshed.positionSeconds,347);
assert.equal(format.register(encoded,{outcome:'failed'}),null);
assert.equal(format.pack(encoded,edited),encoded);
assert.throws(()=>format.register(input+'#ytb=%notjson',{outcome:'success',tags:['새 태그']}));
assert.throws(()=>format.register(input+'#ytb='+encodeURIComponent(JSON.stringify({v:2})),{outcome:'success',tags:['새 태그']}));
for(const raw of [`https://youtu.be/${id}?t=5s`,`https://www.youtube.com/shorts/${id}`,`https://www.youtube.com/live/${id}`])assert.equal(format.videoId(raw),id);
assert.equal(format.unpack(input).kind,'unmanaged');
assert.equal(format.unpack(input+'#chapter').originalUrl,input+'#chapter');
assert.equal(format.unpack(input+'#ytb='+encodeURIComponent(JSON.stringify({v:2}))).kind,'unsupported');
assert.equal(format.unpack(input+'#ytb=%notjson').kind,'invalid');
assert.equal(format.unpack(registration.url.replace('87s','9'.repeat(400)+'s')).kind,'invalid');
assert.equal(format.unpack(`https://www.youtube.com.evil.example/watch?v=${id}`).kind,'invalid');
assert.throws(()=>format.pack(input,{...edited,positionSeconds:-1}));
assert.throws(()=>format.pack(input,{...edited,status:'unknown'}));
assert.throws(()=>format.pack(input,{...edited,customTags:[42]}));
const cleared={...edited,autoTags:[],customTags:[],removedAutoTags:[],aliases:{}};
assert.equal(format.unpack(format.pack(input,cleared)).kind,'managed');
const report={status:'passed',scope:'pure local serialization; no Chrome bookmark reads or writes',originalUrl:input,encodedUrl:encoded,restored:restored.record,checks:['generation failure does not register','empty initial generation does not register','tag edits and aliases round-trip','status and resume position round-trip','canonical URL is stable','video ID deduplicates link forms','unknown version and broken data preserved as non-managed results','all tags may be removed after registration']};
fs.mkdirSync('.logs',{recursive:true});fs.writeFileSync('.logs/bookmark-url-trial.json',JSON.stringify(report,null,2));console.log(JSON.stringify({status:report.status,checks:report.checks,urlLength:encoded.length},null,2));
