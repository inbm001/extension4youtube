const assert=require('node:assert/strict');
const {exportDraft}=require('../prototypes/common-taxonomy.cjs');
const source=require('../classification-draft.json');
const tainted=structuredClone(source);
tainted.bookmarks=[{title:'PRIVATE_FIXTURE_SENTINEL'}];
tainted.watchHistory={positionSeconds:347};
tainted.prototypeCategories[0].privateNote='PRIVATE_FIXTURE_SENTINEL';
const output=exportDraft(tainted);
assert.deepEqual(Object.keys(output).sort(),['aliasGroups','categories','status','version']);
assert(!JSON.stringify(output).includes('PRIVATE_FIXTURE_SENTINEL'));
assert(!Object.hasOwn(output,'watchHistory'));
assert(!Object.hasOwn(output,'reviewCases'));
assert(!Object.hasOwn(output,'lowerLevel'));
assert.equal(output.status,'draft-not-approved');
output.categories[0].terms.push('fixture');
assert(!source.prototypeCategories[0].terms.includes('fixture'));
const duplicate=structuredClone(source);duplicate.prototypeCategories.push(duplicate.prototypeCategories[0]);
assert.throws(()=>exportDraft(duplicate));
assert.throws(()=>exportDraft({...source,status:'approved'}));
console.log('Passed common draft allowlist, private-field exclusion, source isolation and duplicate ID rejection.');
