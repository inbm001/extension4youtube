const assert=require('node:assert/strict');
const {transition}=require('../prototypes/watch-progress.cjs');
const {register,unpack,pack}=require('../prototypes/bookmark-format.cjs');
const url='https://www.youtube.com/watch?v=0gKJ3pgIqI0';
const progress=(positionSeconds,durationSeconds=100)=>({type:'progress',positionSeconds,durationSeconds});
assert.equal(transition(null,progress(99)),null);
const original=unpack(register(url,{outcome:'success',tags:['베이스'],aliases:{'베이스':['bass']}}).url).record;
let state=transition(original,progress(94.99));
assert.equal(state.status,'watching');
state=transition(state,progress(95));
assert.equal(state.status,'completed');
state=transition(state,progress(20));
assert.equal(state.status,'completed');
assert.equal(state.positionSeconds,20);
state=transition(state,{type:'mark',status:'watching'});
assert.equal(state.status,'watching');
state=transition(state,progress(96));
assert.equal(state.status,'completed');
state=transition(state,{type:'mark',status:'watching'});
state=unpack(pack(url,state)).record;
state=transition(state,progress(97));
assert.equal(state.status,'watching','manual reversion above 95 survives restoration and next progress');
state=transition(state,progress(10));
state=transition(state,progress(95));
assert.equal(state.status,'completed','a new crossing can complete replay');
for(const duration of [0,NaN,Infinity])assert.equal(transition(original,progress(99,duration)).status,'watching');
let fractional=transition(original,progress(95.95,101));
assert.equal(fractional.status,'watching');
fractional=transition(fractional,progress(96,101));
assert.equal(fractional.status,'completed');
fractional=transition(fractional,{type:'mark',status:'watching'});
assert.equal(transition(fractional,progress(96.5,101)).status,'watching');
assert.equal(transition(original,{type:'progress',positionSeconds:99}).status,'watching');
assert.equal(transition(original,{type:'mark',status:'completed'}).status,'completed');
assert.throws(()=>transition(original,progress(-1)));
assert.throws(()=>transition(original,progress(Infinity)));
assert.throws(()=>transition(original,{type:'mark',status:'unknown'}));
assert.equal(original.positionSeconds,0);
assert.equal(original.status,'watching');
assert.deepEqual(state.autoTags,original.autoTags);
assert.deepEqual(state.aliases,original.aliases);
console.log('Passed watch progress, manual status, URL restoration and registration gate checks.');
