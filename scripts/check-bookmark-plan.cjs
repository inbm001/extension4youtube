const assert=require('node:assert/strict');
const {planRegistration:plan}=require('../prototypes/bookmark-plan.cjs');
const format=require('../prototypes/bookmark-format.cjs');
const raw='https://www.youtube.com/watch?v=0gKJ3pgIqI0';
const result={outcome:'success',tags:['베이스'],aliases:{'베이스':['bass']}};
const folder='prototype-folder';
const created=plan(raw,result,folder,[]);
assert.equal(created.kind,'create');
const item={id:'one',parentId:folder,url:created.url};
assert.equal(plan(raw,result,folder,[item]).kind,'noop');
const changed=plan(raw,{...result,tags:['새 태그']},folder,[item]);
assert.equal(changed.kind,'update');assert.equal(changed.id,'one');
assert.equal(plan(raw,result,folder,[item,{...item,id:'two'}]).kind,'conflict');
assert.equal(plan(raw,result,folder,[{id:'ordinary',parentId:folder,url:'https://youtu.be/0gKJ3pgIqI0'}]).reason,'unmanaged-existing-bookmark');
assert.equal(plan(raw,result,folder,[{...item,parentId:'other-folder'}]).kind,'create');
assert.equal(plan(raw,{outcome:'failed'},folder,[item]).kind,'noop');
assert.equal(plan(raw,result,folder,[{...item,url:raw+'#ytb=%broken'}]).reason,'unreadable-matching-bookmark');
const record={...format.unpack(created.url).record,status:'completed',positionSeconds:85,customTags:['練習']};
const personal={...item,url:format.pack(raw,record)};
const update=plan(raw,{...result,tags:['更新']},folder,[personal]);
assert.deepEqual(format.unpack(update.url).record.customTags,['練習']);
assert.equal(format.unpack(update.url).record.status,'completed');
assert.equal(format.unpack(update.url).record.positionSeconds,85);
assert.equal(item.url,created.url);
assert.throws(()=>plan(raw,result,'',[]));
assert.throws(()=>plan(raw,result,folder,[null]));
assert.throws(()=>plan(raw,result,folder,[{parentId:folder,url:created.url}]));
assert.throws(()=>plan(raw,result,folder,[item,{...item,url:raw}]));
assert.throws(()=>plan(raw,{outcome:'success',tags:'베이스'},folder,[]));
assert.throws(()=>plan(raw,{outcome:'success',tags:['  ']},folder,[]));
assert.equal(plan(raw,{outcome:'success',tags:[]},folder,[item]).kind,'noop');
assert.equal(plan(raw,result,folder,[{id:'subfolder',parentId:folder,title:'Folder'}]).kind,'create');
console.log('Passed folder-scoped create/update/noop/conflict planning without bookmark mutations.');
