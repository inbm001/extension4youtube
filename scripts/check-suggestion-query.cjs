const assert=require('node:assert/strict');
const core=require('../search-core');
assert.equal(core.suggestionRemainder('17 sound design','사운드 디자인'),'17');
assert.equal(core.suggestionRemainder('deep learning','딥러닝'),'');
assert.equal(core.suggestionRemainder('agent skills','에이전트 스킬'),'');
assert.equal(core.suggestionRemainder('17 bass','베이스 패턴'),'17');
assert.equal(core.suggestionRemainder('ableton plugin','오디오 플러그인'),'ableton');
const video={title:'',tags:['사운드 디자인'],aliases:{}};
assert(core.matches(video,'sound design','tags'));
assert(!core.matches(video,'sound','tags'),'leftover word reproduces prior narrowing');
assert(core.matches(video,core.suggestionRemainder('sound design','사운드 디자인'),'tags'));
assert(core.tagMatches(video,'사운드 디자인'));
assert.equal(core.suggestionTerm('17 sound design'),'sound design');
assert.equal(core.suggestionTerm('deep learning'),'deep learning');
assert.equal(core.suggestionTerm('ableton plu'),'plu');
assert.equal(core.suggestionTerm(''),'');
const candidates=[{tags:['사운드 디자인'],aliases:{}},{tags:['웹 디자인'],aliases:{'웹 디자인':['web design']}}];
assert.deepEqual(candidates.filter(v=>core.tagMatches(v,core.suggestionTerm('17 sound design'))).map(v=>v.tags[0]),['사운드 디자인']);
console.log('Passed multiword alias consumption, preserved preceding terms and no false leftover-word filtering.');
