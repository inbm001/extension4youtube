const assert=require('node:assert/strict');
const core=require('../prototypes/tag-draft-core.js');
const search=require('../search-core.js');
const source={id:'sample',title:'테스트 영상',tags:['베이스','사운드 디자인'],aliases:{}};
const edit=core.empty(),cache={};
core.remove(source,edit,'베이스');
core.add(source,edit,'피아노');core.aliasRecord('피아노',cache,search.groups);
const saved=JSON.parse(JSON.stringify({edit,cache}));
const updatedSource={...source,tags:[...source.tags,'작곡']};
const restored=core.effective(updatedSource,saved.edit,saved.cache);
assert(!restored.tags.includes('베이스'));
assert(restored.tags.includes('피아노')&&restored.tags.includes('작곡'));
assert(search.matches(restored,'piano','tags'));
const cached=core.aliasRecord('피아노',saved.cache,[]);
assert.deepEqual(cached.aliases,['piano']);
core.add(source,edit,'베이스');assert(core.effective(source,edit,cache).tags.includes('베이스'));
core.add(source,edit,'피아노');assert.equal(edit.customTags.length,1);
assert.deepEqual(source.tags,['베이스','사운드 디자인']);
assert.equal(core.aliasRecord('알수없는태그',cache,search.groups).source,'unresolved');
const oldCache={};
assert.equal(core.aliasRecord('편곡',oldCache,[]).source,'unresolved');
const migrated=JSON.parse(JSON.stringify(oldCache));
assert.deepEqual(core.aliasRecord('편곡',migrated,search.groups),{aliases:['arrangement'],source:'local-dictionary'});
assert.deepEqual(core.aliasRecord('편곡',migrated,[]).aliases,['arrangement']);
const unknown=core.aliasRecord('새로운미지표현',migrated,search.groups);
assert.equal(unknown.source,'unresolved');
assert.deepEqual(unknown.aliases,[]);
const overlap=core.effective({...source,tags:['피아노','작곡']},saved.edit,saved.cache);
assert.equal(overlap.tags.filter(tag=>tag==='피아노').length,1);
assert(overlap.customTags.includes('피아노'));
assert(search.matches(overlap,'piano','tags'));
const variants=core.effective({tags:['PIANO'],aliases:{}},{removedAutoTags:[],customTags:['piano']},{piano:{aliases:['피아노'],source:'local-dictionary'}});
assert.deepEqual(variants.tags,['piano']);
assert(search.matches(variants,'피아노','tags'));
const respelled={tags:['사운드 디자인'],aliases:{}};
const hiddenDraft={removedAutoTags:['사운드디자인'],customTags:[]};
assert.deepEqual(core.effective(respelled,hiddenDraft,{}).tags,[]);
core.add(respelled,hiddenDraft,'사운드 디자인');
assert.deepEqual(hiddenDraft.removedAutoTags,[]);
assert.deepEqual(core.effective(respelled,hiddenDraft,{}).tags,['사운드 디자인']);
const dictionaryCache={};
core.aliasRecord('하네스',dictionaryCache,[['하네스','harness']]);
assert.deepEqual(core.aliasRecord('하네스',dictionaryCache,[['하네스','harness','hanness']]).aliases,['harness','hanness']);
dictionaryCache['하네스']={aliases:['내 표현'],source:'user'};
assert.deepEqual(core.aliasRecord('하네스',dictionaryCache,search.groups).aliases,['내 표현']);
console.log('Passed: edits survive source refresh and JSON restore; custom alias search works; alias cache reused; unknown translations not invented.');
