const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
let current=null,restored=false;
const node=()=>({style:{},setAttribute(){},append(){},focus(){},addEventListener(event,fn){this[event]=fn;},showModal(){this.open=true;},close(){this.open=false;this.closeEvent();},remove(){current=null;}});
const document={activeElement:{focus(){restored=true;}},getElementById:()=>current,createElement(){const n=node();n.addEventListener=(event,fn)=>{if(event==='close')n.closeEvent=fn;};return n;},body:{append(n){current=n;}}};
const context={document};vm.createContext(context);
vm.runInContext(fs.readFileSync('prototypes/extension-overlay.js','utf8'),context);
context.toggleBookmarkOverlay('https://fixture.invalid/view');assert(current.open);
context.toggleBookmarkOverlay('https://fixture.invalid/view');assert.equal(current,null);assert(restored);
context.toggleBookmarkOverlay('https://fixture.invalid/view');assert(current.open);
const manifest=JSON.parse(fs.readFileSync('.logs/extension-assets/manifest.json','utf8'));
assert.deepEqual(manifest.permissions,['activeTab','scripting']);assert(!manifest.host_permissions);
assert(!manifest.permissions.includes('bookmarks'));
assert.deepEqual(manifest.web_accessible_resources.flatMap(rule=>rule.resources),['index.html'],'data-bearing scripts must not be web accessible');
const html=fs.readFileSync('.logs/extension-assets/index.html','utf8');
assert(!/<script(?![^>]*\bsrc=)[^>]*>/i.test(html));
assert(!html.includes('const videos='),'public shell must not embed private dataset');
