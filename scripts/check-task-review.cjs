const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const root=path.resolve('.logs/task-review-fixture');fs.mkdirSync(path.join(root,'.logs'),{recursive:true});
const task={id:'fixture',status:'검토필요',previousStatus:'진행',reviewCanComplete:true,detail:'Partial work remains',review:{artifacts:[]}};
fs.writeFileSync(path.join(root,'tasks.json'),JSON.stringify({tasks:[task]}));
const code=fs.readFileSync('scripts/tasks-server.cjs','utf8').replace("const root=path.resolve(__dirname,'..');",'const root='+JSON.stringify(root)+';').replace("server.listen(8770,'127.0.0.1'","server.listen(0,'127.0.0.1'");
const context={require,process,console:{log(){},error:console.error},URL,__dirname:path.resolve('scripts')};vm.createContext(context);vm.runInContext(code,context);
const server=vm.runInContext('server',context);
(async()=>{try{
  if(!server.listening)await new Promise(resolve=>server.once('listening',resolve));
  const base='http://127.0.0.1:'+server.address().port;
  const send=(payload,origin='http://127.0.0.1:8770',route='/review')=>fetch(base+route,{method:'POST',headers:{origin,'Content-Type':'application/json'},body:JSON.stringify(payload)});
  assert.equal((await send({id:'fixture',expected:JSON.stringify(task)},'https://unrelated.example')).status,403);
  assert.equal((await send({id:'fixture',expected:'stale'})).status,409);
  assert.equal((await send({id:'fixture',expected:JSON.stringify(task)})).status,200);
  const stored=JSON.parse(fs.readFileSync(path.join(root,'tasks.json'))).tasks[0];
  assert.equal(stored.status,'완료');assert.equal(stored.detail,task.detail);assert.equal(stored.reviewedBy,'사용자');assert(stored.reviewedAt);
  assert.equal((await send({id:'fixture',expected:JSON.stringify(task)})).status,409);
  assert.equal((await fetch(base+'/review-artifact?id=fixture&index=0')).status,404);
  assert.equal((await send({id:'fixture',expected:JSON.stringify(stored),comment:'내용 보완 필요'},undefined,'/review-comment')).status,200);
  const commented=JSON.parse(fs.readFileSync(path.join(root,'tasks.json'))).tasks[0];
  assert.equal(commented.status,'완료');assert.equal(commented.reviewComments[0].text,'내용 보완 필요');
  assert.equal((await send({id:'fixture',expected:JSON.stringify(commented),comment:' '},undefined,'/review-comment')).status,400);
  const pending={...task,id:'pending',reviewCanComplete:false};
  fs.writeFileSync(path.join(root,'tasks.json'),JSON.stringify({tasks:[pending]}));
  assert.equal((await send({id:'pending',expected:JSON.stringify(pending)})).status,409);
  assert.equal((await send({id:'pending',expected:JSON.stringify(pending),comment:'자료가 필요합니다'},undefined,'/review-comment')).status,200);
  assert.equal(JSON.parse(fs.readFileSync(path.join(root,'tasks.json'))).tasks[0].status,'검토필요');
  const snapshot=JSON.parse(fs.readFileSync(path.join(root,'tasks.json'))).tasks[0];
  assert.equal((await send({id:'pending',expected:JSON.stringify(snapshot),status:'완료'},undefined,'/task-status')).status,400);
  assert.equal((await send({id:'pending',expected:JSON.stringify(snapshot),status:'닫힘'},undefined,'/task-status')).status,200);
  const closed=JSON.parse(fs.readFileSync(path.join(root,'tasks.json'))).tasks[0];
  assert.equal(closed.status,'닫힘');assert.equal(closed.statusHistory.at(-1).from,'검토필요');
  assert.equal((await send({id:'pending',expected:JSON.stringify(closed),status:'unknown'},undefined,'/task-status')).status,400);
  console.log('Passed review persistence, partial-work preservation, stale/repeated rejection, origin boundary and missing artifact.');
}finally{await new Promise(resolve=>server.close(resolve));}})().catch(e=>{console.error(e);process.exitCode=1;});
