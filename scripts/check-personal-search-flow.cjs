const assert=require('node:assert/strict');
const fs=require('node:fs');
const drafts=require('../prototypes/tag-draft-core.js');
const search=require('../search-core.js');
const format=require('../prototypes/bookmark-format.cjs');
const raw='https://www.youtube.com/watch?v=u2oDdU6z4Bw';
const source={id:'u2oDdU6z4Bw',title:'pstack',tags:['pstack'],aliases:{}};
const edit=drafts.empty(),cache={};
drafts.add(source,edit,'하네스');drafts.aliasRecord('하네스',cache,search.groups);
drafts.remove(source,edit,'pstack');
const effective=drafts.effective(source,edit,cache);
assert(search.matches(effective,'hanness','tags'));
assert(search.matches(effective,'harness','tags'));
assert(!search.matches(effective,'pstack','tags'));
const registered=format.unpack(format.register(raw,{outcome:'success',tags:source.tags}).url).record;
const record={...registered,customTags:edit.customTags,removedAutoTags:edit.removedAutoTags,aliases:effective.aliases,status:'completed',positionSeconds:347};
const restored=format.unpack(format.pack(raw,record)).record;
const restoredDraft={customTags:restored.customTags,removedAutoTags:restored.removedAutoTags};
const restoredCache=Object.fromEntries(restored.customTags.map(tag=>[search.normalize(tag),{aliases:restored.aliases[tag],source:'saved-record'}]));
const after=drafts.effective({...source,tags:restored.autoTags},restoredDraft,restoredCache);
after.status=restored.status;
assert(search.matches(after,'harness','tags'));
assert(search.inCategory(after,'ai'));
assert(search.inWatchStatus(after,'completed'));
assert(!search.inWatchStatus(after,'watching'));
assert(!search.matches(after,'pstack','tags'));
assert.equal(restored.positionSeconds,347);
fs.writeFileSync('.logs/personal-search-flow.json',JSON.stringify({scope:'Synthetic composition of local modules. No browser or Chrome bookmark writes.',checks:['custom memory tag added','known typo/English aliases searchable','removed automatic tag excluded','URL round-trip preserves edits, status and position','AI category and completed filter combine']},null,2)+'\n');
console.log('Passed custom memory tag → aliases → hidden auto tag → URL restore → category/status search composition.');
