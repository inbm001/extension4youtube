const assert=require('node:assert/strict');
const {prepareRegistration,revalidateUpdate}=require('../prototypes/bookmark-adapter.cjs');
const format=require('../prototypes/bookmark-format.cjs');
(async()=>{
  const raw='https://www.youtube.com/watch?v=0gKJ3pgIqI0',folder='fixture';
  const result={outcome:'success',tags:['new']};
  const item={id:'one',parentId:folder,url:format.register(raw,{outcome:'success',tags:['old']}).url};
  let items=[item],calls=[];
  const api={getChildren:async id=>{calls.push(id);return structuredClone(items);}};
  const plan=await prepareRegistration(raw,result,folder,api);
  assert.equal(plan.kind,'update');
  assert.equal((await revalidateUpdate(plan,api)).kind,'ready');
  items=[item,{...item,id:'duplicate'}];
  assert.equal((await revalidateUpdate(plan,api)).kind,'stale');
  items=[item,{id:'broken',parentId:folder,url:raw+'#ytb=%broken'}];
  assert.equal((await revalidateUpdate(plan,api)).kind,'stale');
  items=[item,{id:'unrelated',parentId:folder,url:'https://www.youtube.com/watch?v=bJwF79UI-Ao'}];
  assert.equal((await revalidateUpdate(plan,api)).kind,'ready');
  items=[{...item,url:raw}];
  assert.equal((await revalidateUpdate(plan,api)).kind,'stale');
  items=[];
  assert.equal((await revalidateUpdate(plan,api)).kind,'stale');
  items=[{...item,parentId:'moved'}];
  assert.equal((await revalidateUpdate(plan,api)).kind,'stale');
  assert(calls.every(id=>id===folder));
  const denied={getChildren:async()=>{throw Error('fixture permission denied');}};
  await assert.rejects(prepareRegistration(raw,result,folder,denied),/permission denied/);
  assert.equal(item.url,plan.expectedUrl);
  console.log('Passed injected read adapter, stale URL/deletion/move and propagated read failure. No write API exists.');
})().catch(error=>{console.error(error);process.exitCode=1;});
